(function translatePage() {
    const toggle = document.getElementById('langToggle');
    if (toggle) {
        toggle.textContent = LANG === 'en' ? 'FR' : 'EN';
        toggle.setAttribute('aria-label', LANG === 'en' ? 'Version française' : 'English version');
        toggle.addEventListener('click', () => {
            try { localStorage.setItem(LANG_KEY, LANG === 'en' ? 'fr' : 'en'); } catch { }
            location.reload();
        });
    }
    if (LANG !== 'en') return;
    document.documentElement.lang = 'en';

    const ATTRS = ['aria-label', 'title', 'placeholder', 'alt', 'data-title', 'data-rpg', 'data-fallback', 'data-text'];
    const swap = (raw) => {
        const key = raw.replace(/\s+/g, ' ').trim();
        const en = key && EN[key];
        if (!en) return null;
        // on garde les espaces autour du texte (ils séparent les mots des balises voisines)
        const lead = /^\s/.test(raw) ? ' ' : '';
        const trail = /\s$/.test(raw) ? ' ' : '';
        return lead + en + trail;
    };
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode: (n) => n.parentElement.closest('script, style, .cv-modal-body') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(n => { const v = swap(n.nodeValue); if (v) n.nodeValue = v; });
    document.querySelectorAll(ATTRS.map(a => `[${a}]`).join(',')).forEach(el => {
        ATTRS.forEach(a => {
            if (!el.hasAttribute(a)) return;
            const v = swap(el.getAttribute(a));
            if (v) el.setAttribute(a, v.trim());
            else if (a === 'alt' && /^Logo /.test(el.getAttribute(a))) el.setAttribute(a, `${el.getAttribute(a).slice(5)} logo`);
        });
    });
})();
